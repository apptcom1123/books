import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const catalog = JSON.parse(fs.readFileSync(path.join(ROOT, "data", "catalog.json"), "utf8"));
const output = path.join(ROOT, "server", "db", "library-seed.sql");

function sqlText(value) {
  return value == null ? "null" : `'${String(value).replaceAll("'", "''")}'`;
}

function sqlJson(value) {
  return `${sqlText(JSON.stringify(value ?? []))}::jsonb`;
}

const rows = catalog.map((book) => `(
  ${sqlText(book.id)}, ${sqlText(book.source)}, ${sqlText(book.source_id)},
  ${sqlText(book.title_original)}, ${sqlText(book.title_zh)}, ${sqlText(book.author)}, ${Number(book.author_death_year)},
  ${sqlText(book.description_zh)}, ${sqlText(book.category)}, ${sqlText(book.subcategory)}, ${sqlText(book.language || "en")},
  ${sqlText(book.edition_release_date)}, ${sqlJson(book.subjects)}, ${sqlText(book.source_url)},
  ${sqlText(book.epub_url)}, ${sqlText(book.cover_url)}, ${sqlText(book.sha256)}, ${Number(book.file_size)},
  ${sqlText(book.license_status)}, ${sqlText(book.local_copyright_check)}, ${sqlText(book.rights_status)}, ${Number(book.catalog_order)}, true
)`);

const sql = `-- Generated by npm run seed. Run after library-schema.sql in the Supabase SQL Editor.
-- No secret/service-role key is required by the deployed Vercel application.
begin;

do $$
begin
  if to_regclass('public.library_books') is null then
    raise exception 'LIBRARY_SCHEMA_REQUIRED'
      using hint = 'Run server/db/library-schema.sql successfully before this seed file.';
  end if;
end
$$;

insert into public.library_books (
  id, source, source_id, title_original, title_zh, author, author_death_year,
  description_zh, category, subcategory, language, edition_release_date,
  subjects, source_url, epub_url, cover_url, sha256, file_size,
  license_status, local_copyright_check, rights_status, catalog_order, enabled
)
values
${rows.join(",\n")}
on conflict (id) do update set
  source = excluded.source,
  source_id = excluded.source_id,
  title_original = excluded.title_original,
  title_zh = excluded.title_zh,
  author = excluded.author,
  author_death_year = excluded.author_death_year,
  description_zh = excluded.description_zh,
  category = excluded.category,
  subcategory = excluded.subcategory,
  language = excluded.language,
  edition_release_date = excluded.edition_release_date,
  subjects = excluded.subjects,
  source_url = excluded.source_url,
  epub_url = excluded.epub_url,
  cover_url = excluded.cover_url,
  sha256 = excluded.sha256,
  file_size = excluded.file_size,
  license_status = excluded.license_status,
  local_copyright_check = excluded.local_copyright_check,
  rights_status = excluded.rights_status,
  catalog_order = excluded.catalog_order,
  enabled = excluded.enabled,
  updated_at = now();

commit;
`;

fs.writeFileSync(output, sql, "utf8");
console.log(`Generated ${path.relative(ROOT, output)} with ${catalog.length} books.`);
